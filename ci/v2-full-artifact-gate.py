#!/usr/bin/env python3
"""Fail-closed final gate for a complete PU2PNY-V2 SD image.

Usage: python3 ci/v2-full-artifact-gate.py IMAGE.img.xz MOUNTED_ROOTFS EVIDENCE.json

EVIDENCE is a record generated by real CI tests, not a substitute for tests.
No missing file, failed check or unknown result can be promoted to a release.
"""
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

MAX_BYTES = 80_000_000
# Only known names from 5.x builders and the V2 panel. Add other required
# modules after mapping their real on-image paths and validating their tests.
REQUIRED = {
    "backend": ["usr/local/bin/2pnyd", "etc/systemd/system/2pnyd.service"],
    "rf": ["usr/local/bin/MMDVM-Host", "usr/local/bin/DMRGateway"],
    "display": ["usr/local/bin/MMDVM-Display",
                "usr/local/bin/NextionDriver-pu2pny"],
    "network": ["usr/local/sbin/2pny-network-core",
                "usr/local/sbin/2pny-wifi-profiles"],
    "panel": ["usr/share/2pny/" + name for name in (
        "dashboard.html", "hotspot.html", "internet.html", "direct.html",
        "aprs.html", "history.html", "display.html", "system.html",
        "expert.html", "ui-common-0.3.0.js", "ui-language.js",
        "ui-0.3.0.css")],
}
# This is intentionally broader than package-presence: real functionality,
# unmodified baseline and security must have independently generated evidence.
CHECKS = (
    "boot", "arm_abi", "services", "api", "rf_baseline",
    "dmr", "dstar", "ysf", "p25", "nxdn", "pocsag",
    "network_ap_sta_ethernet", "wifi_rollback", "mdns",
    "display_on7lds", "oled_lcd", "aprs_dprs", "direct",
    "history", "helix_off_fallback", "update_backup_recovery",
    "pt_en_es", "secret_redaction", "rootfs_integrity",
)


def verify(image, rootfs, evidence):
    image, rootfs, evidence = Path(image), Path(rootfs), Path(evidence)
    report = {"classification": "NOT_DELIVERED", "limit_bytes": MAX_BYTES,
              "actual_bytes": None, "sha256": None, "missing_files": [],
              "failed_checks": [], "xz": "NOT_VERIFIED"}
    if image.is_file() and image.name.endswith(".img.xz"):
        size = image.stat().st_size
        report["actual_bytes"] = size
        report["under_80mb"] = 0 < size <= MAX_BYTES
        report["sha256"] = hashlib.sha256(image.read_bytes()).hexdigest()
        xz = subprocess.run(["xz", "-t", str(image)], capture_output=True)
        report["xz"] = "PASS" if xz.returncode == 0 else "FAIL"
    else:
        report["under_80mb"] = False
    if rootfs.is_dir() and rootfs.resolve() != Path("/"):
        for component, paths in REQUIRED.items():
            for path in paths:
                if not (rootfs / path).is_file():
                    report["missing_files"].append(component + ":" + path)
    else:
        report["missing_files"].append("rootfs:NOT_VERIFIED")
    if evidence.is_file():
        try:
            data = json.loads(evidence.read_text())
            results = data.get("checks", {})
            report["failed_checks"] = [check for check in CHECKS
                                       if results.get(check) != "PASS"]
            # Prevent declaring a complete firmware using only the known
            # core paths: require an audited inventory with every component.
            report["inventory_complete"] = data.get("inventory_complete") is True
            report["source_commit"] = data.get("source_commit")
        except (ValueError, TypeError):
            report["failed_checks"] = list(CHECKS)
            report["inventory_complete"] = False
    else:
        report["failed_checks"] = list(CHECKS)
        report["inventory_complete"] = False
    passed = (report["under_80mb"] and report["xz"] == "PASS"
              and not report["missing_files"] and not report["failed_checks"]
              and report["inventory_complete"])
    if passed:
        report["classification"] = "SW_CANDIDATE_FOR_HW_TEST"
    return report, passed


if __name__ == "__main__":
    if len(sys.argv) != 4:
        raise SystemExit("usage: gate IMAGE.img.xz MOUNTED_ROOTFS EVIDENCE.json")
    result, passed = verify(*sys.argv[1:])
    print(json.dumps(result, indent=2, sort_keys=True))
    sys.exit(0 if passed else 1)
